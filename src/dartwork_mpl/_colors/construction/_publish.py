"""Render the generated colour module and publish it atomically.

Responsibility: turn a compiled ``CatalogSnapshot`` and the validated v6
authority into the exact bytes of ``_colors/_generated.py`` (deterministic:
sorted keys, no timestamps), and replace a target file through an fsynced
sibling temporary. Gating and the decision to publish belong to the
``python -m dartwork_mpl._colors._build`` entry point.

Surface (through ``dartwork_mpl._colors.construction``): ``render_generated`` and
``atomic_write_text``.
"""

import os
import stat
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import cast

from .._ssot import load_color_v6_ssot
from ._catalog import CatalogSnapshot

__all__ = ["atomic_write_text", "render_generated"]

_HEADER = '''"""AUTO-GENERATED by dartwork_mpl._colors._build — do not edit.

Regenerate: python -m dartwork_mpl._colors._build
Source of truth: asset/color/color_v6_ssot.json (NeutralTone authority).
"""

'''


def _fmt(name: str, table: Mapping[str, Sequence[str]]) -> str:
    lines = [f"{name}: dict[str, tuple[str, ...]] = {{"]
    for key in sorted(table):
        row = ", ".join(f'"{h}"' for h in table[key])
        lines.append(f'    "{key}": ({row}),')
    lines.append("}\n")
    return "\n".join(lines)


def _fmt_multi_hue_indices(
    manifest: Mapping[str, Mapping[str, Sequence[int]]],
) -> str:
    """Format the validated index manifest as a deterministic literal."""
    lines = [
        "MULTI_HUE_DISCRETE_INDICES: dict[str, dict[int, tuple[int, ...]]] = {"
    ]
    for family in sorted(manifest):
        lines.append(f'    "{family}": {{')
        for size_text in sorted(manifest[family], key=int):
            row = manifest[family][size_text]
            values = ", ".join(str(index) for index in row)
            if len(row) == 1:
                values += ","
            lines.append(f"        {int(size_text)}: ({values}),")
        lines.append("    },")
    lines.append("}\n")
    return "\n".join(lines)


def render_generated(candidate: CatalogSnapshot) -> str:
    """Render the complete expected generated module without side effects."""
    authority = load_color_v6_ssot()
    multi_hue_indices = cast(
        Mapping[str, Mapping[str, Sequence[int]]],
        authority.multi_hue_discrete_indices,
    )
    body = (
        _fmt("PALETTE", candidate.palette)
        + "\n"
        + _fmt("CYCLES", candidate.cycles)
        + "\n"
        + _fmt("CMAPS_256", candidate.cmaps_256)
        + "\n"
        + _fmt_multi_hue_indices(multi_hue_indices)
    )
    return _HEADER + body


def _set_temporary_mode(descriptor: int, temporary: Path, mode: int) -> None:
    """Set temporary permissions through the best platform capability."""
    fchmod = getattr(os, "fchmod", None)
    if callable(fchmod):
        fchmod(descriptor, mode)
        return
    os.chmod(temporary, mode)


def atomic_write_text(target: Path, text: str) -> None:
    """Fsync a unique sibling temporary and atomically replace ``target``."""
    target_mode = (
        stat.S_IMODE(target.stat().st_mode) if target.exists() else 0o644
    )
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{target.name}.", suffix=".tmp", dir=target.parent
    )
    temporary = Path(temporary_name)
    descriptor_owned = True
    try:
        _set_temporary_mode(descriptor, temporary, target_mode)
        stream = os.fdopen(descriptor, "w", encoding="utf-8", newline="")
        descriptor_owned = False
        with stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    finally:
        if descriptor_owned:
            os.close(descriptor)
        temporary.unlink(missing_ok=True)
